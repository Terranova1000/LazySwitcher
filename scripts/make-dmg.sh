#!/usr/bin/env bash
# Собирает DMG штатным hdiutil, без внешних зависимостей.
#
# Почему DMG, а не ZIP: приложение, запущенное из ~/Downloads после распаковки
# ZIP, попадает под App Translocation — система монтирует его копию в случайную
# папку только для чтения, настройки перестают сохраняться, и понять причину
# невозможно. Сам образ от этого не спасает: запуск прямо из смонтированного DMG
# приводит к тому же. Снимает перенос через Finder — ради него в окне и лежит
# ярлык «Программы».
set -euo pipefail
cd "$(dirname "$0")/.."
APP="${1:?путь к .app}"
VERSION=$(/usr/libexec/PlistBuddy -c "Print :CFBundleShortVersionString" "$APP/Contents/Info.plist")
NAME="Lazy Switcher"
OUT="dist/LazySwitcher-$VERSION.dmg"
STAGE=$(mktemp -d)

mkdir -p dist
rm -f "$OUT"
cp -R "$APP" "$STAGE/"
ln -s /Applications "$STAGE/Программы"

cat > "$STAGE/Как установить.txt" <<'EOS'
Lazy Switcher — установка

ШАГ 1. Перетащите «Lazy Switcher» в папку «Программы» рядом.
       Именно перетащите. Запуск прямо из этого окна сломает сохранение
       настроек: macOS монтирует образ только для чтения.

ШАГ 2. Откройте приложение из папки «Программы».

       macOS скажет, что не может проверить разработчика. Это ожидаемо:
       у программы нет платной подписи Apple и не будет — она бесплатная.
       Вредоносного в ней ничего нет, но проверить это система не умеет.

       Как открыть:
         Системные настройки → Конфиденциальность и безопасность →
         пролистать вниз → «Всё равно открыть»

       Или одной командой в Терминале — тогда предупреждения не будет вовсе:
         xattr -dr com.apple.quarantine "/Applications/Lazy Switcher.app"

ШАГ 3. Приложение попросит доступ к Универсальному доступу.
       Без него macOS не даст ему видеть, что вы набираете, — а без этого
       оно не работает.

         Системные настройки → Конфиденциальность и безопасность →
         Универсальный доступ → включить «Lazy Switcher»

       После этого приложение перезапустится само. Так надо: система
       сообщает о выданном доступе только новому процессу.

ГОТОВО. Значок появится в строке меню наверху справа.

Наберите слово не в той раскладке и поставьте пробел — исправится само.
Двойной Shift исправляет вручную: выделенный текст, последнее слово,
или откатывает только что сделанную замену.
Левый и правый Shift вместе — пауза.

О ПРИВАТНОСТИ
Приложение видит нажатия клавиш — иначе оно не смогло бы работать.
Набранное живёт в оперативной памяти несколько секунд и стирается: ни в
файл, ни в журнал оно не попадает. В сеть приложение не выходит, кроме
проверки обновлений, которая выключена по умолчанию.

Когда система включает защищённый ввод — окно входа, менеджер паролей,
поле пароля обычного приложения — нажатия до программы просто не доходят.
На сайтах этот режим не включает ни один браузер, поэтому там поле пароля
распознаётся по разметке страницы: в Safari работает, в Chrome и Firefox
нет — и потому в них по умолчанию доступно только ручное исправление.

Требуется macOS 14 или новее.
EOS

# Иконка тома: приятнее и сразу узнаётся в Finder
if [ -f "$APP/Contents/Resources/AppIcon.icns" ]; then
  cp "$APP/Contents/Resources/AppIcon.icns" "$STAGE/.VolumeIcon.icns"
  SetFile -a C "$STAGE" 2>/dev/null || true
fi

hdiutil create -volname "$NAME" -srcfolder "$STAGE" -ov -format UDZO "$OUT" >/dev/null
rm -rf "$STAGE"

echo "· $OUT  ($(du -h "$OUT" | cut -f1))"
hdiutil verify "$OUT" >/dev/null && echo "· образ проверен"
